function findClosingParenthesis(contents, openingIndex) {
  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let index = openingIndex; index < contents.length; index += 1) {
    const character = contents[index];
    if (quote) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === quote) quote = null;
      continue;
    }
    if (character === "'" || character === '"') quote = character;
    else if (character === '(') depth += 1;
    else if (character === ')') {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  return -1;
}

function addExpoLynxPostInstall(contents) {
  const markerIndex = [generatedMarker, legacyGeneratedMarker]
    .map((marker) => contents.indexOf(marker))
    .find((index) => index !== -1);
  if (markerIndex !== undefined) {
    const requireIndex = contents.indexOf('\nrequire ', markerIndex);
    if (requireIndex !== -1) return `${rubyHelper}${contents.slice(requireIndex + 1)}`;
  }
  const functionIndex = contents.indexOf('react_native_post_install(');
  if (functionIndex === -1)
    throw new Error('expo-lynx-view could not find react_native_post_install in the iOS Podfile.');
  const openingIndex = contents.indexOf('(', functionIndex);
  const closingIndex = findClosingParenthesis(contents, openingIndex);
  if (closingIndex === -1)
    throw new Error('expo-lynx-view could not parse the react_native_post_install call.');
  return `${rubyHelper}\n${contents.slice(0, closingIndex + 1)}\n\n    expo_lynx_post_install(installer)${contents.slice(closingIndex + 1)}`;
}

function addExpoLynxSpecsSource(contents) {
  // Lynx/PrimJS/LynxService/XElement/DebugRouter/LynxDevtool/BaseDevtool are
  // only published on the lynx-family Specs repo, not CocoaPods trunk (trunk
  // mirrors some Lynx pods, but not every version — notably not every stable
  // 4.x). A Podfile with no explicit `source` line falls back to trunk only
  // (see CocoaPods' Installer::Analyzer#sources), so without this line
  // CocoaPods silently can't find pods pinned to a version trunk lacks. This
  // must be generated by the plugin, not hand-edited into the native
  // project — a gitignored `ios/Podfile` is rebuilt from scratch on every
  // `expo prebuild --clean` and a manual edit will not survive that.
  let result;
  try {
    result = mergeContents({
      tag: SPECS_SOURCE_TAG,
      src: contents,
      newSrc: `source 'https://cdn.cocoapods.org/'\nsource '${LYNX_SPECS_REPO_URL}'`,
      anchor: /^platform :ios/m,
      offset: 0,
      comment: '#',
    });
  } catch (error) {
    if (error.code === 'ERR_NO_MATCH')
      throw new Error('expo-lynx-view could not find `platform :ios` in the iOS Podfile.');
    throw error;
  }
  return result.contents;
}

function addExpoLynxPrecompiledPod(contents) {
  // ExpoLynx.podspec depends on the bare `Lynx` pod name (via `Lynx/Framework`),
  // which CocoaPods would otherwise resolve from the lynx-family Specs repo as
  // full C++ SOURCE (slow to compile, and it fights newer Xcode's -Werror).
  // This :path override redirects every `Lynx` requirement in the whole
  // graph to the prebuilt ios/Precompiled/Lynx.xcframework instead. It must
  // be generated by the plugin, not hand-edited into the native project —
  // same reasoning as addExpoLynxSpecsSource: a gitignored `ios/Podfile` is
  // rebuilt from scratch on `expo prebuild --clean` and won't keep a manual
  // edit. Losing this line silently falls back to the source pod, which then
  // fights the vendored xcframework for the same Objective-C class names
  // (e.g. `LynxPerformanceController`) — a duplicate-interface build error,
  // not a missing-pod error, so it's easy to miss the real cause.
  //
  // Only called when devTool is off (see withExpoLynx) — LynxDevtool is
  // built from source and reaches into Lynx's internal C++ headers via
  // nested quoted includes (e.g. `#include "base/include/value/base_value.h"`).
  // A compiled .framework flattens every header into one Headers/
  // directory, losing that nested path, so those includes can't resolve
  // against the precompiled xcframework no matter what search paths are
  // added — confirmed with a real `xcodebuild`: LynxDevtool's
  // white_board_inspector_impl.cc failed with "'base/include/value/base_value.h'
  // file not found" even though the file exists (flattened) in the
  // xcframework's PrivateHeaders. Letting Lynx resolve from source instead
  // whenever devTool is on gives LynxDevtool the real, nested source tree it
  // expects — slower Debug+devTool builds, but Release and devTool:false
  // builds still get the fast precompiled path.
  const precompiledPath = path.join(__dirname, 'ios', 'Precompiled');
  if (!fs.existsSync(path.join(precompiledPath, 'Lynx.podspec'))) {
    throw new Error(
      `expo-lynx-view could not find a precompiled Lynx at ${precompiledPath}. ` +
        'Build it with packages/expo-lynx/precompile-host/bump-lynx-version.sh <version>, ' +
        'or copy a prebuilt one from the codex/precompile-lynx branch.'
    );
  }
  let result;
  try {
    result = mergeContents({
      tag: LYNX_PRECOMPILED_POD_TAG,
      src: contents,
      newSrc: `  pod 'Lynx', :path => '${precompiledPath.replace(/'/g, "\\'")}'`,
      anchor: /use_expo_modules!/,
      offset: 0,
      comment: '#',
    });
  } catch (error) {
    if (error.code === 'ERR_NO_MATCH')
      throw new Error('expo-lynx-view could not find use_expo_modules! in the iOS Podfile.');
    throw error;
  }
  return result.contents;
}

function removeExpoLynxPrecompiledPod(contents) {
  // Mirrors addExpoLynxDevtoolPod's toggle handling: called when devTool is
  // on, so a prior devTool:false prebuild's :path override doesn't linger
  // and fight the source-resolved Lynx that LynxDevtool needs.
  return removeContents({ tag: LYNX_PRECOMPILED_POD_TAG, src: contents }).contents;
}

function addExpoLynxDevtoolPod(contents) {
  // LynxService/Devtool pulls in LynxDevtool, BaseDevtool, and DebugRouter
  // transitively. `:configurations` on a Podfile pod line does NOT propagate
  // to that pod's own dependencies — CocoaPods only restricts the exact pod
  // it's attached to, so scoping just LynxService/Devtool still links
  // LynxDevtool/BaseDevtool/DebugRouter into Release. Each has to be scoped
  // explicitly. `:configurations` only works here, in the app's Podfile — a
  // podspec's `s.dependency` silently ignores it and would still link
  // DebugRouter into Release hosts.
  let result;
  try {
    result = mergeContents({
      tag: DEVTOOL_POD_TAG,
      src: contents,
      newSrc: [
        `  pod 'LynxService/Devtool', '${IOS_LYNX_VERSION}', :configurations => ['Debug']`,
        `  pod 'LynxDevtool', '${IOS_LYNX_VERSION}', :configurations => ['Debug']`,
        `  pod 'BaseDevtool', '${IOS_LYNX_VERSION}', :configurations => ['Debug']`,
        `  pod 'DebugRouter', '${DEBUG_ROUTER_VERSION}', :configurations => ['Debug']`,
      ].join('\n'),
      anchor: /use_expo_modules!/,
      offset: 0,
      comment: '#',
    });
  } catch (error) {
    if (error.code === 'ERR_NO_MATCH')
      throw new Error('expo-lynx-view could not find use_expo_modules! in the iOS Podfile.');
    throw error;
  }
  return result.contents;
}

function removeExpoLynxDevtoolPod(contents) {
  // Mirrors addExpoLynxDevtoolPod so a prebuild that flips `devTool` from
  // true to false (without a clean) strips a previously injected line
  // instead of leaving it stale in the regenerated Podfile.
  return removeContents({ tag: DEVTOOL_POD_TAG, src: contents }).contents;
}

